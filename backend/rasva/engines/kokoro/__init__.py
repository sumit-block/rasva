"""Kokoro-82M narration engine (phase A1 lightweight baseline, PRD §14-15).

Runs the official ``kokoro`` package (PyTorch, CPU) inside its own Python 3.12
environment built from ``requirements.lock`` (ADR-0003). All model files come from
``manifest.json``: pinned to one Hugging Face commit with SHA-256 per file, and
generated by ``scripts/pin_kokoro.py``. At runtime the engine only reads local
files; ``HF_HUB_OFFLINE=1`` in the worker turns any accidental hub lookup into an
error rather than a download.

Module import must stay light: the API process imports this file to describe
the engine, and it has neither torch nor numpy.
"""

from __future__ import annotations

import json
import time
import wave
from pathlib import Path
from typing import Any

from rasva.audio.text import detect_script, script_counts, segment
from rasva.engines.contract import (
    CompatibilityReport,
    Engine,
    EngineDescriptor,
    EngineInputError,
    InstallContext,
    ModelArtifact,
    OutputFile,
    RunContext,
    RunResult,
    RuntimeContext,
    SystemFacts,
    Voice,
)

REPO_ID = "hexgrad/Kokoro-82M"
MODEL_FILE = "kokoro-v1_0.pth"
CONFIG_FILE = "config.json"
SAMPLE_RATE = 24_000
MAX_CHARS = 5_000  # A1 is short narration; long-form chunked jobs arrive in A4
PREVIEW_MAX_SEGMENTS = 1
PHONEME_LIMIT = 510  # Kokoro truncates longer phoneme strings
PEAK_CEILING = 0.97  # keep exports below clipping (PRD §29.3)
MANIFEST_PATH = Path(__file__).with_name("manifest.json")

# Kokoro voice ids encode language and gender: a=US English, b=UK English,
# h=Hindi; f=female, m=male. Only voices listed in manifest.json are offered.
VOICE_CATALOGUE: list[Voice] = [
    Voice(id="af_heart", display_name="Heart", language="en", accent="American", gender="female"),
    Voice(id="af_bella", display_name="Bella", language="en", accent="American", gender="female"),
    Voice(id="af_nicole", display_name="Nicole", language="en", accent="American", gender="female"),
    Voice(id="am_michael", display_name="Michael", language="en", accent="American", gender="male"),
    Voice(id="am_adam", display_name="Adam", language="en", accent="American", gender="male"),
    Voice(id="bf_emma", display_name="Emma", language="en", accent="British", gender="female"),
    Voice(id="bm_george", display_name="George", language="en", accent="British", gender="male"),
    Voice(id="hf_alpha", display_name="Alpha", language="hi", gender="female"),
    Voice(id="hf_beta", display_name="Beta", language="hi", gender="female"),
    Voice(id="hm_omega", display_name="Omega", language="hi", gender="male"),
    Voice(id="hm_psi", display_name="Psi", language="hi", gender="male"),
]
DEFAULT_VOICE = {"en": "af_heart", "hi": "hf_alpha"}


def load_manifest(path: Path = MANIFEST_PATH) -> dict[str, Any] | None:
    if not path.is_file():
        return None
    data = json.loads(path.read_text(encoding="utf-8"))
    if data.get("repo") != REPO_ID or not data.get("revision"):
        raise ValueError("Kokoro manifest is for a different repository or has no revision")
    return data


def artifacts_from(manifest: dict[str, Any] | None) -> list[ModelArtifact]:
    if not manifest:
        return []
    base = f"https://huggingface.co/{REPO_ID}/resolve/{manifest['revision']}"
    return [
        ModelArtifact(path=f["path"], url=f"{base}/{f['path']}", sha256=f["sha256"],
                      size_bytes=f["size_bytes"])
        for f in manifest["files"]
    ]  # fmt: skip


def voices_from(manifest: dict[str, Any] | None) -> list[Voice]:
    if not manifest:
        return []
    pinned = {f["path"] for f in manifest["files"]}
    return [v for v in VOICE_CATALOGUE if f"voices/{v.id}.pt" in pinned]


_MANIFEST = load_manifest()
_ARTIFACTS = artifacts_from(_MANIFEST)
_WEIGHTS_BYTES = sum(a.size_bytes for a in _ARTIFACTS)
# Estimate for torch + spaCy + transformers on macOS arm64 plus a managed
# Python 3.12; replaced by the measured size after installation.
_ENV_ESTIMATE_BYTES = 1_600 * 1024**2


class KokoroEngine(Engine):
    descriptor = EngineDescriptor(
        id="kokoro-82m",
        display_name="Kokoro",
        summary=(
            "A small, fast voice engine. Natural English; basic Hindi. "
            "Roman Hinglish is read with English pronunciation."
        ),
        version="1.0",
        modality="audio",
        tasks=["audio.narrate"],
        languages=["English", "Hindi"],
        features=["preset_voices", "speed", "preview"],
        license="Apache-2.0 (model and code)",
        license_class="permissive",
        license_notes=[
            "Hindi and some English words are pronounced with espeak-ng and phonemizer, "
            "which are GPL-3.0 licensed. They are installed on your Mac from PyPI and run "
            "only inside Kokoro's own environment.",
        ],
        source_url=f"https://huggingface.co/{REPO_ID}",
        approx_download_bytes=_WEIGHTS_BYTES,
        approx_installed_bytes=_WEIGHTS_BYTES + _ENV_ESTIMATE_BYTES,
        approx_peak_memory_bytes=2 * 1024**3,
        artifacts=_ARTIFACTS,
        requirements_lock="requirements.lock",
        python_version="3.12",
        voices=voices_from(_MANIFEST),
    )

    def __init__(self) -> None:
        self._model: Any = None
        self._pipelines: dict[str, Any] = {}
        self._model_dir: Path | None = None

    # ---- control plane ----

    def check_compatibility(self, system: SystemFacts) -> CompatibilityReport:
        reasons = []
        if not self.descriptor.artifacts:
            reasons.append(
                "Kokoro's download list has not been pinned yet, so it cannot be installed "
                "safely. Run scripts/pin_kokoro.py once."
            )
        if not system.apple_silicon:
            reasons.append("Kokoro's software package is built for Apple Silicon Macs.")
        return CompatibilityReport(compatible=not reasons, reasons=reasons)

    def verify(self, ctx: InstallContext) -> bool:
        return (
            all(
                (ctx.model_dir / a.path).is_file()
                and (ctx.model_dir / a.path).stat().st_size == a.size_bytes
                for a in self.descriptor.artifacts
            )
            and (ctx.model_dir / MODEL_FILE).is_file()
            and (ctx.model_dir / CONFIG_FILE).is_file()
        )

    # ---- runtime (worker only) ----

    def validate_input(self, task: str, inputs: dict[str, Any]) -> dict[str, Any]:
        if task != "audio.narrate":
            raise EngineInputError(f"Kokoro cannot do '{task}'.")
        text = str(inputs.get("text") or "").strip()
        if not text:
            raise EngineInputError("Write or paste some text to narrate.")
        if len(text) > MAX_CHARS:
            raise EngineInputError(
                f"Kokoro narrates up to {MAX_CHARS:,} characters at a time for now. "
                "Split the script into shorter parts."
            )
        voices = {v.id: v for v in self.descriptor.voices}
        voice_id = str(inputs.get("voice_id") or "")
        voice = voices.get(voice_id)
        if voice is None:
            raise EngineInputError("Choose one of Kokoro's voices.")
        script = detect_script(text)
        # English G2P silently skips words it cannot read, so any Devanagari would
        # vanish from the audio rather than be mispronounced.
        if voice.language == "en" and script_counts(text)["devanagari"] > 0:
            raise EngineInputError(
                "This text contains Hindi in Devanagari. Choose a Hindi voice, or write it "
                "in Roman letters for an English voice."
            )
        try:
            speed = float(inputs.get("speed", 1.0))
        except (TypeError, ValueError) as exc:
            raise EngineInputError("Speed must be a number.") from exc
        if not 0.5 <= speed <= 2.0:
            raise EngineInputError("Speed must be between 0.5× and 2×.")
        return {
            "text": text,
            "voice_id": voice_id,
            "speed": round(speed, 2),
            "preview": bool(inputs.get("preview", False)),
            "language": voice.language,
            "script": script,
        }

    def load(self, ctx: RuntimeContext) -> None:
        from kokoro import KModel  # heavy import: worker process only

        self._model_dir = ctx.model_dir
        self._model = (
            KModel(
                repo_id=REPO_ID,
                config=str(ctx.model_dir / CONFIG_FILE),
                model=str(ctx.model_dir / MODEL_FILE),
            )
            .to("cpu")
            .eval()
        )

    def _pipeline(self, lang_code: str) -> Any:
        if lang_code not in self._pipelines:
            from kokoro import KPipeline

            self._pipelines[lang_code] = KPipeline(
                lang_code=lang_code, repo_id=REPO_ID, model=self._model
            )
        return self._pipelines[lang_code]

    def run(self, task: str, inputs: dict[str, Any], ctx: RunContext) -> RunResult:
        import numpy as np

        assert self._model is not None and self._model_dir is not None, "load() not called"
        voice_id = inputs["voice_id"]
        voice_path = str(self._model_dir / "voices" / f"{voice_id}.pt")
        pipeline = self._pipeline(voice_id[0])  # 'a', 'b' or 'h'

        segments = segment(inputs["text"])
        if inputs["preview"]:
            segments = segments[:PREVIEW_MAX_SEGMENTS]
        if not segments:
            raise EngineInputError("There is nothing to narrate in this text.")

        started = time.perf_counter()
        chunks: list[Any] = []
        timeline: list[dict[str, Any]] = []
        cursor = 0
        truncated = 0
        for k, seg in enumerate(segments):
            ctx.raise_if_canceled()
            ctx.report_progress(k / len(segments), f"Sentence {k + 1} of {len(segments)}")
            pieces = []
            for result in pipeline(seg.text, voice=voice_path, speed=inputs["speed"],
                                   split_pattern=None):  # fmt: skip
                if result.audio is None:
                    continue
                if len(result.phonemes or "") >= PHONEME_LIMIT:
                    truncated += 1
                pieces.append(np.asarray(result.audio, dtype=np.float32).reshape(-1))
            audio = np.concatenate(pieces) if pieces else np.zeros(0, dtype=np.float32)
            pause = np.zeros(int(seg.pause_after_s * SAMPLE_RATE), dtype=np.float32)
            is_last = k == len(segments) - 1
            chunks.append(audio)
            timeline.append(
                {
                    "index": seg.index,
                    "text": seg.text,
                    "start_s": round(cursor / SAMPLE_RATE, 3),
                    "end_s": round((cursor + len(audio)) / SAMPLE_RATE, 3),
                }
            )
            cursor += len(audio)
            if not is_last:
                chunks.append(pause)
                cursor += len(pause)

        signal = np.concatenate(chunks) if chunks else np.zeros(0, dtype=np.float32)
        if signal.size == 0 or not np.any(signal):
            raise EngineInputError("Kokoro produced no sound for this text.")
        peak = float(np.max(np.abs(signal)))
        if peak > PEAK_CEILING:
            signal = signal * (PEAK_CEILING / peak)
        pcm = (np.clip(signal, -1.0, 1.0) * 32767).astype("<i2")

        ctx.report_progress(1.0, "Saving audio")
        out = ctx.output_dir / "narration.wav"
        with wave.open(str(out), "wb") as wav:
            wav.setnchannels(1)
            wav.setsampwidth(2)
            wav.setframerate(SAMPLE_RATE)
            wav.writeframes(pcm.tobytes())

        duration = len(pcm) / SAMPLE_RATE
        elapsed = time.perf_counter() - started
        return RunResult(
            outputs=[
                OutputFile(
                    filename="narration.wav",
                    media_type="audio/wav",
                    metadata={
                        "kind": "preview" if inputs["preview"] else "narration",
                        "engine": "kokoro-82m",
                        "model_revision": (_MANIFEST or {}).get("revision"),
                        "voice_id": voice_id,
                        "language": inputs["language"],
                        "speed": inputs["speed"],
                        "duration_s": round(duration, 3),
                        "sample_rate": SAMPLE_RATE,
                        "segments": timeline,
                        "synthetic": True,  # PRD §11, §28 disclosure
                    },
                )
            ],
            metrics={
                "audio_s": round(duration, 3),
                "synthesis_s": round(elapsed, 3),
                "real_time_factor": round(elapsed / duration, 4) if duration else None,
                "segments": len(segments),
                "truncated_segments": truncated,
                "device": "cpu",
                "peak_before_limit": round(peak, 4),
            },
        )

    def unload(self) -> None:
        self._pipelines.clear()
        self._model = None
